#!/bin/sh
#
# 四段增益「听感跟着变」验收 —— **在板上跑**。
#
#     sh gain_ab_live.sh
#
# 做的是：起一趟 66 秒的实时通路（麦克风 -> 核 -> 耳机），
# 跑的过程中往 /dev/shm/fir_tune.json 写不同的每段增益，
# 让人**在变化发生的当下**听出来。
#
# 为什么不用「跑两趟、参数不同、事后回忆着比」：
#   靠记忆 A/B 本来就弱，而且对称设置（低段 +6 / 高段 -6）总响度几乎不变，
#   只有音色微变 —— 2026-10-15 实测那一组用户听不出来。
#   要让人听出来，得让**单段的电平真的大幅改变**。
#
# 时间线（每档 12 秒）：
#     0-12s   平（全 0 dB）        基准
#    12-24s   段0 -41.9 dB         低频段整个压掉 -> 声音变「薄」
#    24-36s   平                   变回来
#    36-48s   段3 -41.9 dB         高频段整个压掉 -> 声音变「闷」
#    48-60s   平                   变回来
#    60-66s   段0 -41.9 dB         再压一次，确认可重复
#
# 判据只有一条：人耳朵听出每一档的变化。数字侧同时看
#   · `[调参] 增益 ...` 六行 —— 证明改动被接住了
#   · 逐位自检 `[OK] 960000/960000` —— 证明"边拖滑杆边跑"也没算错
#
# 2026-10-15 实测：六次改动全部被接住；自检在"增益变过 8 次"的前提下逐位通过；
# 实时倍率 1.00x；进核 rms 中位 1221 / P90 4047 / 峰 29651；用户听到几次明显变化。
# 原始输出：`data/results/fir_gain_ab_run_20261015.txt`。
#
# -41.9 dB 是 `fir_live.py` 的 GAIN_LIMIT_DB，也是 Q7.8 能表示的下限
# （1.0 == 256，最小 1/256 再往下就编不出来）。
#
cd /home/xilinx/jupyter_notebooks || exit 1
T=/dev/shm/fir_tune.json

setg() {
    printf '{"gain_db":[%s]}\n' "$1" > "$T"
    echo ">>> 增益置为 [$1] dB（低→高）  @$(date +%M:%S)"
}

setg "0,0,0,0"

LIVE_EXTRA='LIVE_VOLUME=35 LIVE_DIAG=1' sh run_live.sh 66 > /tmp/ab_live.log 2>&1 &
PID=$!

sleep 12; setg "-41.9,0,0,0"
sleep 12; setg "0,0,0,0"
sleep 12; setg "0,0,0,-41.9"
sleep 12; setg "0,0,0,0"
sleep 12; setg "-41.9,0,0,0"

wait $PID
setg "0,0,0,0"
echo "==================== 跑完 ===================="
grep -a "电平\] \|OK \]\|倍率\|进核的电平" /tmp/ab_live.log
